/*  strada, fuoristrada, suv, motocross */
create table categorie (
	id_categoria int generated by default as identity,
	nome_cat varchar(30),
	primary key (id_categoria)
);

create table tipoVeicolo (
	id_tipoVeicolo int generated by default as identity,
	nome_tipo varchar(30),
	primary key (id_tipoVeicolo),
	constraint check_tipo check(id_tipoVeicolo in (1, 2, 3)
);

create table tipoAlimentazione (
	id_tipoAlimentazione int generated by default as identity,
	nome_alim varchar(30),
	primary key (id_tipoAlimentazione)
);

create table colori (
	id_colore int generated by default as identity,
	nome_colore varchar(30),
	primary key (id_colore)
);

create table marche (
	id_marca int generated by default as identity,
	nome_marca varchar(30),
	primary key (id_marca)
);

create table veicoli (
	id_veicolo int generated by default as identity,
	id_tipoVeicolo int not null,
	numeroRuote int not null,
	id_tipoAlimentazione int not null,
	id_categoria int not null,
	id_colore int not null,
	id_marca int not null,
	annoProduzione int  not null check(annoProduzione >= 2006 and annoProduzione <= 2026),
	modello varchar(50) not null,
	primary key (id_veicolo),
	foreign key (id_categoria) references categorie(id_categoria),
	foreign key (id_tipoVeicolo) references tipoVeicolo(id_tipoVeicolo),
	foreign key (id_tipoAlimentazione) references tipoAlimentazione(id_tipoAlimentazione),
	foreign key (id_colore) references colori(id_colore),
	foreign key (id_marca) references marche(id_marca),
	CONSTRAINT chk_categoria_tipo_veicolo CHECK (
    (id_tipoVeicolo = 1 AND id_categoria IN (1, 2, 3))
    OR
    (id_tipoVeicolo = 2 AND id_categoria IN (4, 5, 6))
    OR
    (id_tipoVeicolo = 3 AND id_categoria IN (7, 8, 9)))
);

check((tipo='Bici' and sospenzione IN(senza,con, bi) or (tipo='Macchina' and sospenzione IN(...)) or(tipo='Moto' and sospenzione IN(...)))

