create table macchine (
	id_macchina int generated by default as identity,
	id_veicolo int unique,
	targa varchar(10) unique,
	cilindrata int not null,
	numeroPorte int not null,
	primary key (id_macchina),
	foreign key (id_veicolo) references veicoli(id_veicolo)
);

