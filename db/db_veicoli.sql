create table relazioneVeicoli (
	id_relazioneVeicoli int generated by default as identity,
	id_veicolo int unique,
	id_macchina int unique,
	id_moto int unique,
	id_bici int unique,
	primary key (id_relazioneVeicoli),
	foreign key (id_veicolo) references veicoli(id_veicolo),
	foreign key (id_macchina) references macchine(id_macchina) ,
	foreign key (id_moto) references moto(id_moto),
	foreign key (id_bici) references bici(id_bici) 
);

