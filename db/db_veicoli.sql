create view veicoli_view as
	select v.tipoVeicolo, v.numeroRuote, v.tipoAlimentazione, v.categoria, v.colore, v.marca, v.annoProduzione, v.modello, 
	m.targa, m.cilindrata, m.numeroPorte, mo.targa as moto_targa, mo.cilindrata as cilindrata_moto, b.numeroMarce, 
	b.tipoSospensione, b.pieghevole from veicoli v
	join relazioneVeicoli rv on v.id_veicolo = rv.id_veicolo
	left join macchine m on m.id_macchina = rv.id_macchina
	left join moto mo on mo.id_moto = rv.id_moto
	left join bici b on b.id_bici = rv.id_bici

select * from veicoli_view;

