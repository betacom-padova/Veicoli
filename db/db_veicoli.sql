create table bici (
	id_bici int generated by default as identity,
	id_veicolo int unique,
	numeroMarce int not null,
	id_sospensione int not null,
	pieghevole boolean not null,
	primary key (id_bici),
	foreign key (id_veicolo) references veicoli(id_veicolo),
	foreign key (id_sospensione) references sospensione(id_sospensione)
);

